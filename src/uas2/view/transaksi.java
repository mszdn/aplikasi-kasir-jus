    private void hitungTotalPembayaran() {
        DefaultTableModel dtm = (DefaultTableModel) jTable3.getModel();
        int total = 0;

        for (int i = 0; i < dtm.getRowCount(); i++) {
            total += Double.parseDouble(dtm.getValueAt(i, 4).toString());
        }

        texttotalpembayaran.setText(String.valueOf(total));
    }
    
    private void hitungKembalian() {
        try {
            double total = Double.parseDouble(texttotalpembayaran.getText());
            double bayar = Double.parseDouble(textbayar.getText());
            double kembali = bayar - total;

            textkembali.setText(String.valueOf(kembali >= 0 ? kembali : 0));
        } catch (NumberFormatException e) {
            textkembali.setText("0");
        }
    }


