    private void btncetakpdfActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncetakpdfActionPerformed
        // TODO add your handling code here:
        Document document = new Document();
        String outputPath = null;

        try {
            // Pilih lokasi simpan PDF
            JFileChooser chooser = new JFileChooser();
            chooser.setSelectedFile(new File("laporan.pdf"));

            int result = chooser.showSaveDialog(this);

            if (result == JFileChooser.APPROVE_OPTION) {
                File file = chooser.getSelectedFile();
                outputPath = file.getAbsolutePath();

                // Tambahkan .pdf jika user tidak menulis ekstensi
                if (!outputPath.toLowerCase().endsWith(".pdf")) {
                    outputPath += ".pdf";
                }
            } else {
                JOptionPane.showMessageDialog(this, "Penyimpanan dibatalkan.");
                return; // berhenti
            }

            // Writer PDF
            PdfWriter.getInstance(document, new java.io.FileOutputStream(outputPath));
            document.open();

            // Judul Laporan
            document.add(new Paragraph("LAPORAN TRANSAKSI"));
            document.add(new Paragraph("Kasir : " + kasirLogin.getUsername()));
            document.add(new Paragraph("Tanggal Cetak : " + new java.util.Date().toString()));
            document.add(new Paragraph("---------------------------------------------------------"));
            document.add(new Paragraph("\n"));

            // Buat tabel PDF
            PdfPTable pdfTable = new PdfPTable(jTable1.getColumnCount());

            // Header kolom
            for (int i = 0; i < jTable1.getColumnCount(); i++) {
                PdfPCell cell = new PdfPCell(new Paragraph(jTable1.getColumnName(i)));
                pdfTable.addCell(cell);
            }

            // Isi tabel
            for (int row = 0; row < jTable1.getRowCount(); row++) {
                for (int col = 0; col < jTable1.getColumnCount(); col++) {
                    Object value = jTable1.getValueAt(row, col);
                    pdfTable.addCell(value == null ? "" : value.toString());
                }
            }

            // Tambahkan tabel ke PDF
            document.add(pdfTable);

            // Tambahkan Total Pendapatan
            document.add(new Paragraph("\n"));
            document.add(new Paragraph("Total Pendapatan : " + jTextField1.getText()));

            document.close();

            JOptionPane.showMessageDialog(this, 
                    "PDF berhasil dibuat!\nLokasi: " + outputPath);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, 
                    "Gagal membuat PDF: " + e.getMessage());
            e.printStackTrace();
        }
        
    }//GEN-LAST:event_btncetakpdfActionPerformed

