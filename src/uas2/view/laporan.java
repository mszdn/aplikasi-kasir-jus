    private void tampilkanKeTabel(List<Laporan> data) {
        DefaultTableModel model = new DefaultTableModel(
            new String[]{"No", "Tanggal", "Pelanggan", "Total", "IDKasir"}, 0
        );

        int totalPendapatan = 0;

        for (Laporan l : data) {
            model.addRow(new Object[]{
                    l.getIdTransaksi(),
                    l.getTanggal(),
                    l.getPelanggan(),
                    l.getTotal(),
                    l.getIdKasir()
            });

            totalPendapatan += l.getTotal();
        }

        jTable1.setModel(model);
        jTextField1.setText(String.valueOf(totalPendapatan));
    }


